#!/usr/bin/env python3
"""
Generates resources/lib/home/fontwidths.py: the advance widths of the characters
of Noto Sans, the font of Estuary for font10 to font14. The TV interface wraps
the titles of the tiles itself with them: Kodi cannot tell how many lines a
text takes, and a textbox neither grows nor ends a cut text with an ellipsis.

    python3 .scripts/generate_font_widths.py /usr/share/kodi/addons/skin.estuary/fonts/NotoSans-Regular.ttf

Needs Pillow.
"""

import os
import sys

from PIL import ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TARGET = os.path.join(ROOT, 'resources', 'lib', 'home', 'fontwidths.py')

# Latin-1, Latin Extended-A and the punctuation that shows up in titles
RANGES = ((0x20, 0x7e), (0xa0, 0x17f), (0x2010, 0x2026), (0x2030, 0x203a), (0x20ac, 0x20ac), (0x2122, 0x2122))


def main(font_path):
    font = ImageFont.truetype(font_path, 1000)
    widths = {}
    for first, last in RANGES:
        for code in range(first, last + 1):
            widths[code] = int(round(font.getlength(chr(code))))
    letters = [widths[code] for code in range(ord('a'), ord('z') + 1)]
    lines = ['# -*- coding: utf-8 -*-',
             '"""',
             'Advance widths of Noto Sans in thousandths of the font size.',
             'Generated by .scripts/generate_font_widths.py - do not edit manually.',
             '',
             'SPDX-License-Identifier: MIT',
             '"""',
             '',
             '# characters missing below: a bit wider than the average small letter',
             'DEFAULT = %d' % (sum(letters) * 1.2 / len(letters)),
             '',
             'WIDTHS = {']
    codes = sorted(widths)
    for start in range(0, len(codes), 8):
        lines.append('    ' + ' '.join('%d: %d,' % (code, widths[code]) for code in codes[start:start + 8]))
    lines.append('}')
    with open(TARGET, 'w', encoding='utf-8') as out:
        out.write('\n'.join(lines) + '\n')
    print('Generated %s (%d characters)' % (os.path.relpath(TARGET, ROOT), len(widths)))


if __name__ == '__main__':
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
